create function public.soundspin_archive_moderation(p_room text,p_old jsonb,p_new jsonb) returns void language plpgsql security invoker set search_path='' as $$
declare v_kind text;entry jsonb;replacement jsonb;v_record_id text;record_time bigint;active boolean; previous_array jsonb; next_array jsonb;
begin
 if jsonb_typeof(p_new)<>'object' or octet_length(p_new::text)>4194304 then raise exception 'Invalid or oversized moderation document.';end if;
 if p_new?'receipts' and (jsonb_typeof(p_new->'receipts')<>'object' or (select count(*) from jsonb_object_keys(p_new->'receipts'))>1000) then raise exception 'Too many room action receipts.';end if;
 foreach v_kind in array array['log','reports','restrictions','warnings','inviteLinks','cancelledInvitations'] loop
  next_array:=coalesce(p_new->v_kind,'[]'::jsonb);
  if jsonb_typeof(next_array)<>'array' then raise exception 'Invalid moderation collection.';end if;
  if jsonb_array_length(next_array)>(case v_kind when 'log' then 500 when 'reports' then 1500 when 'warnings' then 2500 when 'inviteLinks' then 550 when 'cancelledInvitations' then 500 else 10500 end) then raise exception 'Moderation collection limit reached.';end if;
  previous_array:=coalesce(p_old->v_kind,'[]'::jsonb);
  if jsonb_typeof(previous_array)<>'array' then
   insert into public.soundspin_moderation_archive(room_slug,kind,record_id,data,created_at,archived_at) values(p_room,'legacy-document',md5(p_old::text),p_old,0,now()) on conflict do nothing;
   previous_array:='[]'::jsonb;
  end if;
  for entry in select value from jsonb_array_elements(previous_array) loop
   v_record_id:=case when v_kind='cancelledInvitations' then entry#>>'{}' else coalesce(entry->>'id',md5(entry::text)) end;
   select value into replacement from jsonb_array_elements(next_array) where (case when v_kind='cancelledInvitations' then value#>>'{}' else coalesce(value->>'id',md5(value::text)) end)=v_record_id limit 1;
   if found then
    if v_kind='log' and replacement is distinct from entry then raise exception 'Moderation history is append-only';end if;
    continue;
   end if;
   active:=case v_kind
    when 'reports' then entry->>'status'='open'
    when 'warnings' then entry->>'readAt' is null
    when 'restrictions' then entry->>'revokedAt' is null and (entry->>'expiresAt' is null or case when entry->>'expiresAt'~'^[0-9]{1,16}$' then (entry->>'expiresAt')::numeric>extract(epoch from now())*1000 else true end)
    when 'inviteLinks' then entry->>'revokedAt' is null and case when entry->>'expiresAt'~'^[0-9]{1,16}$' then (entry->>'expiresAt')::numeric>extract(epoch from now())*1000 else true end
    else false end;
   if coalesce(active,true) then raise exception 'Active moderation evidence cannot be archived.';end if;
   record_time:=case when entry->>'createdAt'~'^[0-9]{1,16}$' then (entry->>'createdAt')::bigint else 0 end;
   if exists(select 1 from public.soundspin_moderation_archive a where a.room_slug=p_room and a.kind=v_kind and a.record_id=v_record_id and a.data is distinct from entry) then raise exception 'Archived moderation history is immutable.';end if;
   insert into public.soundspin_moderation_archive(room_slug,kind,record_id,data,created_at,archived_at) values(p_room,v_kind,v_record_id,entry,record_time,now()) on conflict do nothing;
  end loop;
 end loop;
end $$;
revoke all on function public.soundspin_archive_moderation(text,jsonb,jsonb) from public,anon,authenticated;

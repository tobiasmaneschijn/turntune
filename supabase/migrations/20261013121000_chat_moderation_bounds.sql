-- Account erasure anonymizes identity links while retained abuse evidence follows
-- the documented retention/legal-hold policy. Free-form text requires rights review.
-- Only structured identity fields are erasure work. Owner-controlled names,
-- descriptions, URLs and retained evidence must not hold another user's job open.
create function public.soundspin_has_account_identity(p_value jsonb,p_user text) returns boolean language plpgsql immutable set search_path='' as $$
declare field text; value jsonb;
begin
 -- A cheap prefilter avoids walking unrelated documents; text alone never
 -- decides whether an identity exists or whether erasure is complete.
 if p_value is null or position(p_user in p_value::text)=0 then return false;end if;
 case jsonb_typeof(p_value)
 when 'object' then
  if p_value->>'id'=p_user and p_value?'name' and p_value?'avatarSeed' then return true;end if;
  for field,value in select key,v.value from jsonb_each(p_value) v loop
   if field=any(array['userId','user_id','actorId','actor_id','reporterId','reporter_id','targetUserId','target_user_id','createdBy','resolvedBy','revokedBy','authorId','ownerUserId','djUserId']) and value=to_jsonb(p_user) then return true;end if;
   if field=any(array['moderatorUserIds','djRoleUserIds','djQueueUserIds','userIds','uses']) and jsonb_typeof(value)='array' and value @> jsonb_build_array(p_user) then return true;end if;
   if field=any(array['members','rulesAcceptance','djQueues','votes']) and jsonb_typeof(value)='object' and value?p_user then return true;end if;
   if field='receipts' and jsonb_typeof(value)='object' and exists(select 1 from jsonb_object_keys(value) k where split_part(k,':',1)=p_user) then return true;end if;
   if public.soundspin_has_account_identity(value,p_user) then return true;end if;
  end loop;
 when 'array' then
  for value in select v.value from jsonb_array_elements(p_value) v loop
   if public.soundspin_has_account_identity(value,p_user) then return true;end if;
  end loop;
 else null;
 end case;
 return false;
end $$;
revoke all on function public.soundspin_has_account_identity(jsonb,text) from public,anon,authenticated;
grant execute on function public.soundspin_has_account_identity(jsonb,text) to service_role;

create function public.soundspin_scrub_account_identity(p_value jsonb,p_user text,p_label text) returns jsonb language plpgsql immutable set search_path='' as $$
declare result jsonb; field text; value jsonb;
begin
 case jsonb_typeof(p_value)
 when 'object' then
  if p_value->>'id'=p_user and p_value?'name' and p_value?'avatarSeed' then return jsonb_build_object('id',p_label,'name','Deleted account','avatarSeed','deleted-account');end if;
  result:='{}'::jsonb;
  for field,value in select key,v.value from jsonb_each(p_value) v loop
   if field=any(array['userId','user_id','actorId','actor_id','reporterId','reporter_id','targetUserId','target_user_id','createdBy','resolvedBy','revokedBy','authorId','ownerUserId','djUserId']) and value=to_jsonb(p_user) then value:=to_jsonb(p_label);
   elsif field=any(array['moderatorUserIds','djRoleUserIds','djQueueUserIds','userIds','uses']) and jsonb_typeof(value)='array' then
    select coalesce(jsonb_agg(v.value order by v.ordinal),'[]'::jsonb) into value from jsonb_array_elements(value) with ordinality v(value,ordinal) where v.value is distinct from to_jsonb(p_user);
   elsif field=any(array['members','rulesAcceptance','djQueues','votes']) and jsonb_typeof(value)='object' then value:=value-p_user;
   elsif field='receipts' and jsonb_typeof(value)='object' then
    select coalesce(jsonb_object_agg(k,v),'{}'::jsonb) into value from jsonb_each(value) e(k,v) where split_part(k,':',1)<>p_user;
   end if;
   result:=result||jsonb_build_object(field,public.soundspin_scrub_account_identity(value,p_user,p_label));
  end loop;return result;
 when 'array' then
  select coalesce(jsonb_agg(public.soundspin_scrub_account_identity(v.value,p_user,p_label) order by v.ordinal),'[]'::jsonb) into result from jsonb_array_elements(p_value) with ordinality v(value,ordinal);return result;
 else return p_value;
 end case;
end $$;
revoke all on function public.soundspin_scrub_account_identity(jsonb,text,text) from public,anon,authenticated;

create function public.soundspin_scrub_archived_identity(p_value jsonb,p_user text) returns jsonb language plpgsql immutable set search_path='' as $$
begin
 return public.soundspin_scrub_account_identity(p_value,p_user,'[deleted-account]');
end $$;
revoke all on function public.soundspin_scrub_archived_identity(jsonb,text) from public,anon,authenticated;
create function public.soundspin_erase_archived_account(p_user uuid,p_limit integer default 1000) returns jsonb language plpgsql security definer set search_path='' as $$
declare moderation_count integer; child_count integer; message_count integer; remaining boolean;
begin
 if p_user is null or p_limit not between 1 and 1000 then raise exception 'Invalid archive erasure batch.';end if;
 with matches as(select room_slug,kind,record_id from public.soundspin_moderation_archive where public.soundspin_has_account_identity(data,p_user::text) limit p_limit for update skip locked), changed as(update public.soundspin_moderation_archive a set data=public.soundspin_scrub_archived_identity(a.data,p_user::text) from matches x where a.room_slug=x.room_slug and a.kind=x.kind and a.record_id=x.record_id returning 1) select count(*) into moderation_count from changed;
 with matches as(select kind,record_key from public.soundspin_chat_child_archive where data->>'user_id'=p_user::text limit p_limit for update skip locked), removed as(delete from public.soundspin_chat_child_archive a using matches x where a.kind=x.kind and a.record_key=x.record_key returning 1) select count(*) into child_count from removed;
 with matches as(select id from public.soundspin_messages where mentions @> jsonb_build_array(jsonb_build_object('userId',p_user::text)) order by id limit p_limit for update skip locked), changed as(update public.soundspin_messages m set mentions=(select coalesce(jsonb_agg(e.value order by e.ordinal),'[]'::jsonb) from jsonb_array_elements(m.mentions) with ordinality e(value,ordinal) where e.value->>'userId' is distinct from p_user::text) from matches x where m.id=x.id returning 1) select count(*) into message_count from changed;
 select exists(select 1 from public.soundspin_moderation_archive where public.soundspin_has_account_identity(data,p_user::text)) or exists(select 1 from public.soundspin_chat_child_archive where data->>'user_id'=p_user::text) or exists(select 1 from public.soundspin_messages where mentions @> jsonb_build_array(jsonb_build_object('userId',p_user::text))) into remaining;
 return jsonb_build_object('eventsAnonymized',moderation_count,'childrenRemoved',child_count,'messagesScrubbed',message_count,'remaining',remaining);
end $$;
revoke all on function public.soundspin_erase_archived_account(uuid,integer) from public,anon,authenticated;
grant execute on function public.soundspin_erase_archived_account(uuid,integer) to service_role;

-- The application calls these only while holding its per-room command queue.
-- SQL row locks serialize external writers too; the returned document replaces
-- the cached room state immediately, before that room queue is released.
create function public.soundspin_moderation_actor_rooms(p_user uuid,p_after text default null,p_limit integer default 50) returns jsonb language plpgsql security invoker set search_path='' as $$
declare result jsonb;
begin
 if p_user is null or p_limit not between 1 and 50 or char_length(p_after)>48 then raise exception 'Invalid erasure room page.';end if;
 select coalesce(jsonb_agg(slug order by slug),'[]'::jsonb) into result from (
  select r.slug from public.soundspin_rooms r left join public.soundspin_room_moderation m on m.room_slug=r.slug
  where (p_after is null or r.slug>p_after) and (public.soundspin_has_account_identity(r.state,p_user::text) or public.soundspin_has_account_identity(m.data,p_user::text) or public.soundspin_has_account_identity(r.settings,p_user::text)
   or exists(select 1 from public.soundspin_room_members member where member.room_slug=r.slug and member.user_id=p_user))
  order by r.slug limit p_limit
 ) page;
 return result;
end $$;

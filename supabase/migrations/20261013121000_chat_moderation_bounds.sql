create function public.soundspin_erase_live_moderation_account(p_room text,p_user uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare old_state jsonb; old_moderation jsonb; new_state jsonb; new_moderation jsonb; old_settings jsonb; new_settings jsonb; collection text; item jsonb; entries jsonb; timestamp_ms bigint; owner_text text;
begin
 if p_user is null then raise exception 'Invalid account erasure.';end if;
 if to_regclass('public.soundspin_account_restrictions') is not null then
  if not exists(select 1 from public.soundspin_account_restrictions where user_id=p_user and state='deleting') then raise exception 'The account must be in its approved deletion workflow.';end if;
 end if;
 select state,settings into old_state,old_settings from public.soundspin_rooms where slug=p_room for update;
 if not found then return null;end if;
 select data into old_moderation from public.soundspin_room_moderation where room_slug=p_room for update;
 old_moderation:=coalesce(old_moderation,'{}'::jsonb);old_state:=coalesce(old_state,'{}'::jsonb);old_settings:=coalesce(old_settings,'{}'::jsonb);
 timestamp_ms:=floor(extract(epoch from now())*1000)::bigint;
 new_moderation:=old_moderation;
 foreach collection in array array['log','reports','warnings','restrictions','inviteLinks'] loop
  entries:='[]'::jsonb;
  for item in select value from jsonb_array_elements(coalesce(old_moderation->collection,'[]'::jsonb)) loop
   if public.soundspin_has_account_identity(item,p_user::text) then
    if collection='log' then continue;end if; -- The guard archives immutable originals below.
    if collection='warnings' and item->>'userId'=p_user::text then item:=item||jsonb_build_object('readAt',timestamp_ms);end if;
    if collection='reports' and item->>'targetUserId'=p_user::text and item->>'status'='open' then item:=item||jsonb_build_object('status','dismissed','resolvedAt',timestamp_ms,'resolvedBy','system');end if;
    if collection='restrictions' and item->>'userId'=p_user::text then item:=item||jsonb_build_object('revokedAt',timestamp_ms,'revokedBy','system');end if;
    if collection='inviteLinks' and item->>'createdBy'=p_user::text then item:=item||jsonb_build_object('revokedAt',timestamp_ms);end if;
    item:=public.soundspin_scrub_archived_identity(item,p_user::text);
   end if;
   entries:=entries||jsonb_build_array(item);
  end loop;
  new_moderation:=jsonb_set(new_moderation,array[collection],entries,true);
 end loop;
 new_moderation:=jsonb_set(new_moderation,'{members}',coalesce(new_moderation->'members','{}'::jsonb)-p_user::text,true);
 new_moderation:=jsonb_set(new_moderation,'{rulesAcceptance}',coalesce(new_moderation->'rulesAcceptance','{}'::jsonb)-p_user::text,true);
 select coalesce(jsonb_object_agg(key,value),'{}'::jsonb) into entries from jsonb_each(coalesce(new_moderation->'receipts','{}'::jsonb)) where split_part(key,':',1)<>p_user::text and not public.soundspin_has_account_identity(value,p_user::text);
 new_moderation:=jsonb_set(new_moderation,'{receipts}',entries,true);
 new_state:=old_state;
 -- Normalize a legacy shared queue without recreating the deleted user's private queue.
 new_state:=jsonb_set(new_state,'{djQueues}',coalesce(new_state->'djQueues','{}'::jsonb)-p_user::text,true);
 if jsonb_typeof(old_state->'queue')='array' then
  for item in select value from jsonb_array_elements(old_state->'queue') loop
   owner_text:=item#>>'{addedBy,id}';
   if owner_text is not null and owner_text<>p_user::text then
    entries:=coalesce(new_state#>array['djQueues',owner_text],'[]'::jsonb);
    if not exists(select 1 from jsonb_array_elements(entries) t where t.value->>'id'=item->>'id') then entries:=entries||jsonb_build_array(item);end if;
    new_state:=jsonb_set(new_state,array['djQueues',owner_text],entries,true);
    entries:=coalesce(new_state->'djQueueUserIds','[]'::jsonb);
    if not entries?owner_text then new_state:=jsonb_set(new_state,'{djQueueUserIds}',entries||jsonb_build_array(owner_text),true);end if;
   end if;
  end loop;
 end if;
 new_state:=new_state-'queue';
 if old_state->>'djUserId'=p_user::text or (old_state#>>'{playback,track,addedBy,id}'=p_user::text and coalesce(old_state#>>'{playback,origin}','dj')<>'fallback') then
  new_state:=jsonb_set(new_state,'{djUserId}','null'::jsonb,true);
  new_state:=jsonb_set(new_state,'{playback}',jsonb_build_object('track',null,'playing',false,'position',0,'updatedAt',timestamp_ms,'origin','dj','revision',coalesce((old_state#>>'{playback,revision}')::bigint,0)+1),true);
  new_state:=jsonb_set(new_state,'{vibe}','null'::jsonb,true);
 end if;
 if old_state#>>'{radioState,turn,userId}'=p_user::text then new_state:=jsonb_set(new_state,'{radioState}',(new_state->'radioState')-'turn',true);end if;
 new_state:=public.soundspin_scrub_live_room_identity(new_state,p_user::text);
 new_settings:=public.soundspin_scrub_live_room_identity(old_settings,p_user::text);
 new_state:=jsonb_set(new_state,'{settings}',new_settings,true);
 if to_regclass('public.soundspin_room_members') is not null then delete from public.soundspin_room_members where room_slug=p_room and user_id=p_user;end if;
 update public.soundspin_rooms set state=new_state,settings=new_settings,updated_at=now() where slug=p_room;
 if old_moderation is distinct from new_moderation then
  update public.soundspin_room_moderation set data=new_moderation,revision=revision+1,updated_at=now() where room_slug=p_room;
 end if;
 return jsonb_build_object('state',new_state,'moderation',new_moderation);
end $$;
revoke all on function public.soundspin_erase_live_moderation_account(text,uuid) from public,anon,authenticated;
grant execute on function public.soundspin_erase_live_moderation_account(text,uuid) to service_role;

-- Reconcile existing rooms before applying the release gates. Every evicted
-- inactive record is archived by the same guard; active or corrupt permission
-- state fails the migration instead of being silently removed.
do $$
declare room_record record; doc jsonb; collection text; source jsonb; bounded jsonb; receipt_data jsonb;
begin
 if to_regclass('public.soundspin_room_invitations') is not null then
  update public.soundspin_room_invitations i set cancelled_at=coalesce(i.cancelled_at,now())
  from public.soundspin_room_moderation m where m.room_slug=i.room_slug and jsonb_typeof(m.data->'cancelledInvitations')='array'
    and i.id::text in(select jsonb_array_elements_text(m.data->'cancelledInvitations'));
 end if;
 for room_record in select room_slug,data from public.soundspin_room_moderation for update loop
  doc:=room_record.data;
  foreach collection in array array['log','reports','restrictions','warnings','inviteLinks','cancelledInvitations'] loop
   source:=coalesce(doc->collection,'[]'::jsonb);
   if jsonb_typeof(source)<>'array' then raise exception 'Room % has corrupt % evidence; reconcile it before launch.',room_record.room_slug,collection;end if;
   if collection in ('log','cancelledInvitations') then
    select coalesce(jsonb_agg(value order by ordinal),'[]'::jsonb) into bounded from (select value,ordinal from jsonb_array_elements(source) with ordinality as e(value,ordinal) order by ordinal desc limit 500) retained;
   else
    with classified as (
     select value,ordinal,
      case collection
       when 'reports' then coalesce(value->>'status' not in ('resolved','dismissed'),true)
       when 'warnings' then value->>'readAt' is null
       when 'restrictions' then value->>'revokedAt' is null and (value->>'expiresAt' is null or case when value->>'expiresAt'~'^[0-9]{1,16}$' then (value->>'expiresAt')::numeric>extract(epoch from now())*1000 else true end)
       else value->>'revokedAt' is null and case when value->>'expiresAt'~'^[0-9]{1,16}$' then (value->>'expiresAt')::numeric>extract(epoch from now())*1000 else true end end as active
     from jsonb_array_elements(source) with ordinality as e(value,ordinal)
    ), retired as (select ordinal from classified where not active order by ordinal desc limit 500)
    select coalesce(jsonb_agg(value order by ordinal),'[]'::jsonb) into bounded from classified where active or ordinal in(select ordinal from retired);
   end if;
   doc:=jsonb_set(doc,array[collection],bounded,true);
  end loop;
  if jsonb_typeof(coalesce(doc->'receipts','{}'::jsonb))<>'object' then raise exception 'Room % has corrupt replay receipts; reconcile before launch.',room_record.room_slug;end if;
  select coalesce(jsonb_object_agg(key,value),'{}'::jsonb) into receipt_data from jsonb_each(coalesce(doc->'receipts','{}'::jsonb)) where case when value->>'createdAt'~'^[0-9]{1,16}$' then (value->>'createdAt')::numeric>extract(epoch from(now()-interval '24 hours'))*1000 else false end;
  doc:=jsonb_set(doc,'{receipts}',receipt_data,true);
  if doc is distinct from room_record.data then update public.soundspin_room_moderation set data=doc,revision=revision+1,updated_at=now() where room_slug=room_record.room_slug;end if;
 end loop;
 delete from public.soundspin_chat_receipts where created_at<=now()-interval '24 hours';
end $$;

-- Profiles and memberships are paged together; the moderator never loads every
-- profile in the room just to return the first 50 members.
create function public.soundspin_room_member_page(p_room text,p_query text default '',p_cursor text default null,p_limit integer default 50) returns jsonb language plpgsql security invoker set search_path='' as $$
declare offset_value integer; result jsonb; next_cursor text;
begin
 if char_length(p_query)>100 or p_limit not between 1 and 50 or (p_cursor is not null and p_cursor!~'^[0-9]{1,6}$') then raise exception 'Invalid member page.';end if;
 offset_value:=coalesce(p_cursor::integer,0);
 with matched as (
  select m.user_id,case when m.user_id=r.owner_id then 'owner' else m.role end as role,m.joined_at,
   coalesce(p.display_name,'Listener') as display_name,p.avatar_key,p.avatar_url
  from public.soundspin_room_members m join public.soundspin_rooms r on r.slug=m.room_slug left join public.soundspin_profiles p on p.user_id=m.user_id
  where m.room_slug=p_room and (p_query='' or position(lower(p_query) in lower(coalesce(p.display_name,'Listener')))>0)
  order by lower(coalesce(p.display_name,'Listener')),m.user_id limit p_limit+1 offset offset_value
 ), page as (select * from matched order by lower(display_name),user_id limit p_limit)
 select coalesce(jsonb_agg(jsonb_build_object('user',jsonb_strip_nulls(jsonb_build_object('id',user_id,'name',display_name,'avatarSeed',user_id,'avatarKey',avatar_key,'avatarUrl',avatar_url)),'role',role,'joinedAt',floor(extract(epoch from joined_at)*1000)::bigint) order by lower(display_name),user_id),'[]'::jsonb),case when (select count(*) from matched)>p_limit then (offset_value+p_limit)::text else null end into result,next_cursor from page;
 return jsonb_build_object('members',result,'cursor',next_cursor);
end $$;
revoke all on function public.soundspin_room_member_page(text,text,text,integer) from public,anon,authenticated;
grant execute on function public.soundspin_room_member_page(text,text,text,integer) to service_role;


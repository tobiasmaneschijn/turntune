create function public.soundspin_bound_chat_children() returns trigger language plpgsql security invoker set search_path='' as $$
begin
 perform 1 from public.soundspin_messages where id=new.message_id and removed_at is null for update;
 if not found then raise exception 'This message is unavailable.';end if;
 perform pg_advisory_xact_lock(hashtextextended('chat-child:'||new.message_id::text,0));
 if tg_table_name='soundspin_message_reactions' then
  if not exists(select 1 from public.soundspin_chat_reaction_catalog where emoji=new.emoji) then raise exception 'Choose a supported emoji.';end if;
  if not exists(select 1 from public.soundspin_message_reactions where message_id=new.message_id and user_id=new.user_id and emoji=new.emoji) and (
    (select count(*) from public.soundspin_message_reactions where message_id=new.message_id and user_id=new.user_id)>=3 or
    (select count(*) from public.soundspin_message_reactions where message_id=new.message_id)>=300) then raise exception 'This message has reached its reaction limit.';end if;
 else
  if not exists(select 1 from public.soundspin_poll_votes where message_id=new.message_id and user_id=new.user_id) and
    (select count(*) from public.soundspin_poll_votes where message_id=new.message_id)>=300 then raise exception 'This poll has reached its voter limit.';end if;
 end if;
 return new;
end $$;

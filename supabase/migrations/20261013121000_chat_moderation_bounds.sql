create function public.soundspin_read_moderation_archive(p_room text,p_kind text,p_query text default '',p_cursor text default null,p_limit integer default 50) returns jsonb language plpgsql security invoker set search_path='' as $$
declare result jsonb; next_cursor text;
begin
 if p_kind not in ('reports','log','restrictions','warnings') or char_length(p_query)>100 or p_limit not between 1 and 50 or (p_cursor is not null and p_cursor!~'^[0-9]{1,16}:[a-zA-Z0-9_-]{1,100}$') then raise exception 'Invalid archive page.';end if;
 with matched as (
  select data,created_at,record_id from public.soundspin_moderation_archive where room_slug=p_room and kind=p_kind
  and (p_query='' or position(lower(p_query) in lower(data::text))>0)
  and (p_cursor is null or (created_at,record_id)<(split_part(p_cursor,':',1)::bigint,split_part(p_cursor,':',2)))
  order by created_at desc,record_id desc limit p_limit+1
 ), page as (select * from matched order by created_at desc,record_id desc limit p_limit)
 select coalesce(jsonb_agg(data order by created_at desc,record_id desc),'[]'::jsonb),case when (select count(*) from matched)>p_limit then (select created_at::text||':'||record_id from page order by created_at,record_id limit 1) else null end into result,next_cursor from page;
 return jsonb_build_object('items',result,'cursor',next_cursor);
end $$;

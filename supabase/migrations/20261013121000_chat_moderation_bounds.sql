create function public.soundspin_charge_mention(p_user uuid,p_kind text,p_cost integer,p_limit integer) returns void language plpgsql security invoker set search_path='' as $$
declare accepted uuid;
begin
 insert into public.soundspin_chat_mention_budgets(user_id,kind,count,expires_at) values(p_user,p_kind,p_cost,now()+interval '1 minute')
 on conflict(kind,user_id) do update set count=case when public.soundspin_chat_mention_budgets.expires_at<=now() then excluded.count else public.soundspin_chat_mention_budgets.count+excluded.count end,
 expires_at=case when public.soundspin_chat_mention_budgets.expires_at<=now() then excluded.expires_at else public.soundspin_chat_mention_budgets.expires_at end
 where public.soundspin_chat_mention_budgets.expires_at<=now() or public.soundspin_chat_mention_budgets.count+excluded.count<=p_limit returning user_id into accepted;
 if accepted is null or p_cost>p_limit then raise exception 'Mention limit reached. Send a message without mentions.';end if;
end $$;
